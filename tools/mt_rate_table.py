#!/usr/bin/env python3
"""Measure how fast each MacinTalk voice really speaks at each [[rate N]] and
write core/mt/mt_rates.h, which "Same as today's Alex" uses to ask each voice
for the rate that gives the speed it wants.

MacinTalk's rate is not words per minute for every voice. Tiger's formant
voices (Fred, Ralph, Zarvox ...) run away above about 250 (asked 500, they
speak 1281); Leopard's to Lion's compress (asked 1000, 553-703); Tiger's
Vicki, Victoria, Agnes and Bruce level off at 370-600; some novelty voices
collapse to 32 wpm above 180. Alex and the later Vicki are close to exact.

    tools/mt_rate_table.py <mt_golden harness> <extracted dir> > core/mt/mt_rates.h

The harness is tests/mt_golden.c built as tools/build_mt_native.sh builds it
(with recompiled code, or it takes a long time). Needs numpy.
"""
import glob
import os
import subprocess
import sys
import tempfile

import numpy as np

RATES = [60, 90, 120, 150, 180, 220, 260, 300, 350, 400, 450, 500, 600, 700, 800, 1000, 1200, 1500]
TEXT = ("The quick brown fox jumps over the lazy dog while the five boxing wizards jump quickly "
        "and the sphinx of black quartz judges my vow, then everyone goes home for dinner.")
WORDS = len(TEXT.split())
GENS = ["mt104", "mt105", "mt106", "mt107"]
BUILTIN = 3  # mt_golden's own utterances come first


def wpm(path):
    x = np.fromfile(path, np.float32)
    nz = np.nonzero(np.abs(x) > 0.01)[0]
    if len(nz) < 100:
        return 0
    return round(WORDS / ((nz[-1] - nz[0]) / 22050) * 60)


def main():
    harness, extracted = sys.argv[1], sys.argv[2]
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        corpus = os.path.join(tmp, "corpus.txt")
        with open(corpus, "w") as f:
            for r in RATES:
                f.write(f"[[rate {r}]]{TEXT}\n")
        for gen in GENS:
            root = os.path.join(extracted, gen)
            if not os.path.exists(os.path.join(root, "MacinTalk")):
                print(f"skip {gen}: no engine", file=sys.stderr)
                continue
            out = os.path.join(tmp, gen)
            os.mkdir(out)
            env = dict(os.environ, MT_GOLDEN_CORPUS=corpus, MT_GOLDEN_PCM=out)
            subprocess.run([harness, root], env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)
            voices = sorted({os.path.basename(p).split("_t")[0] for p in glob.glob(out + f"/*_t{BUILTIN}_s0.f32")})
            for v in voices:
                rows.append((gen, v, [wpm(f"{out}/{v}_t{i + BUILTIN}_s0.f32") for i in range(len(RATES))]))
    print("// Generated by tools/mt_rate_table.py: the words per minute each MacinTalk")
    print("// voice speaks (measured, the pangram below) when asked for each rate in")
    print("// kMtRateAsked with [[rate N]]. Used by mtengine.c's modern rate curve.")
    print(f"// Text: \"{TEXT}\"")
    print("#pragma once")
    print(f"#define MT_RATE_POINTS {len(RATES)}")
    print("static const short kMtRateAsked[MT_RATE_POINTS] = {" + ", ".join(map(str, RATES)) + "};")
    print("static const struct { const char *gen, *voice; short wpm[MT_RATE_POINTS]; } kMtRates[] = {")
    for gen, v, w in rows:
        print(f'    {{"{gen}", "{v}", {{{", ".join(map(str, w))}}}}},')
    print("};")


if __name__ == "__main__":
    main()
